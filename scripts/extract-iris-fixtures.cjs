/**
 * Reduce the multi-hundred-KB IRIS 2.0 page captures down to committable
 * fixtures: just the heading bars and data rows, with all Angular styling,
 * scripts and chrome stripped out.
 *
 * The captures themselves are ~470KB each and full of inlined CSS/base64, so
 * they are unsuitable for the repo. What the filler actually depends on is a
 * narrow contract:
 *
 *   .heading-bar         → column labels
 *   .tableRows.dataRow[id] → the row, id === IRIS system code
 *   .data-middle-child-wapper > input[disabled?] → the positional cells
 *   .row-description-text  → human label
 *
 * Everything else is noise. Fixtures preserve that contract verbatim.
 *
 * Usage: node scripts/extract-iris-fixtures.cjs [sourceDir]
 * Default sourceDir: ~/uploads
 */

"use strict";

const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");

const { JSDOM } = require("jsdom");

const SOURCE_DIR = process.argv[2] || path.join(os.homedir(), "uploads");
const OUT_DIR = path.join(__dirname, "..", "test-fixtures", "iris");

/** source capture -> fixture name */
const FIXTURES = [
  ["IRIS 2.0 form3.html", "salary.html", "Salary"],
  ["IRIS 2.0 form 5.html", "withholding.html", "Withholding Tax"],
  ["IRIS 2.0 form 6.html", "computations.html", "Computations"],
  ["IRIS 2.0 form 8.html", "assets.html", "Personal Assets / Liabilities"],
  [
    // After adding a bank through the Bank Account(s) modal (2026-10-01).
    "bank account field visibleIRIS 2.0.html",
    "assets-with-bank.html",
    "Personal Assets / Liabilities",
  ],
  [
    "IRIS 2.0 form 9.html",
    "reconciliation.html",
    "Reconciliation of Net Assets",
  ],
  ["IRIS 2.0-form.html", "tax-deductions.html", "Tax Deductions"],
];

// Attributes that carry no meaning for the filler.
const DROP_ATTRS = /^(_ngcontent|_nghost|mattooltip|onkeypress|aria-|role$)/;

function cleanElement(el, doc) {
  for (const attr of [...el.attributes]) {
    if (DROP_ATTRS.test(attr.name)) el.removeAttribute(attr.name);
  }
  // Collapse Angular's noisy class soup to only what selectors need.
  const keep = [
    "heading-bar",
    "columns-parent",
    "tableRows",
    "dataRow",
    "form-head",
    "data-middle-child-wapper",
    "row-description-text",
    "data-first-child",
    "data-tab-left-btn",
    "active",
  ];
  if (el.classList && el.classList.length) {
    const kept = [...el.classList].filter((c) => keep.includes(c));
    el.className = kept.join(" ");
    if (!kept.length) el.removeAttribute("class");
  }
  el.removeAttribute("style");
  for (const child of [...el.children]) cleanElement(child, doc);
}

function extract(sourceFile, outName, sectionLabel) {
  const src = path.join(SOURCE_DIR, sourceFile);
  if (!fs.existsSync(src)) {
    console.warn(`  SKIP  ${sourceFile} (not found in ${SOURCE_DIR})`);
    return false;
  }

  const dom = new JSDOM(fs.readFileSync(src, "utf8"));
  const d = dom.window.document;

  const rows = [...d.querySelectorAll(".tableRows.dataRow[id]")];
  if (!rows.length) {
    console.warn(`  SKIP  ${sourceFile} (no data rows)`);
    return false;
  }

  const out = new JSDOM(
    `<!doctype html><html><head><meta charset="utf-8"><title>IRIS fixture: ${sectionLabel}</title></head><body></body></html>`,
  );
  const od = out.window.document;
  const body = od.body;

  const banner = od.createComment(
    ` IRIS 2.0 fixture — section "${sectionLabel}", derived from "${sourceFile}". ` +
      `Generated by scripts/extract-iris-fixtures.cjs. Structure preserved verbatim; ` +
      `styling/Angular attributes stripped. `,
  );
  body.appendChild(banner);

  // Left-hand section nav, so navigation code can be tested too.
  const leftBtns = [...d.querySelectorAll(".data-tab-left-btn")];
  if (leftBtns.length) {
    const nav = od.createElement("div");
    nav.className = "left-nav";
    for (const b of leftBtns) {
      const btn = od.createElement("button");
      btn.className =
        "data-tab-left-btn" + (b.classList.contains("active") ? " active" : "");
      btn.textContent = b.textContent.replace(/\s+/g, " ").trim();
      nav.appendChild(btn);
    }
    body.appendChild(nav);
  }

  // Walk the document in order so each heading-bar keeps its rows beneath it —
  // the filler resolves headers by walking backwards from a row.
  const interesting = [
    ...d.querySelectorAll(
      ".heading-bar, .tableRows.dataRow[id], .tableRows.form-head",
    ),
  ];
  const container = od.createElement("div");
  container.className = "iris-data";

  for (const node of interesting) {
    // Skip nodes nested inside another captured node (avoids duplication).
    if (interesting.some((other) => other !== node && other.contains(node))) {
      continue;
    }
    const clone = od.importNode(node, true);
    cleanElement(clone, od);
    container.appendChild(clone);
  }

  body.appendChild(container);

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const outPath = path.join(OUT_DIR, outName);
  fs.writeFileSync(outPath, out.serialize(), "utf8");

  const size = (fs.statSync(outPath).size / 1024).toFixed(1);
  console.log(
    `  OK    ${outName}  (${rows.length} rows, ${size}KB) from ${sourceFile}`,
  );
  return true;
}

console.log(`Extracting IRIS fixtures from ${SOURCE_DIR}`);
let ok = 0;
for (const [src, out, label] of FIXTURES) {
  if (extract(src, out, label)) ok += 1;
}
console.log(
  `\n${ok}/${FIXTURES.length} fixtures written to test-fixtures/iris/`,
);
